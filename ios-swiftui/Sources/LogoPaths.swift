// A Shape that renders one or more SVG path strings, scaled from their viewBox
// to fill the given rect. Combined into one Path so a single .fill() covers all.
struct SVGPaths: Shape {
    let paths: [String]
    let viewBox: CGSize

    func path(in rect: CGRect) -> Path {
        var combined = Path()
        for d in paths { combined.addPath(SVGPathParser.parse(d)) }
        let sx = rect.width / viewBox.width
        let sy = rect.height / viewBox.height
        return combined.applying(CGAffineTransform(scaleX: sx, y: sy))
            .applying(CGAffineTransform(translationX: rect.minX, y: rect.minY))
    }
}

// Minimal SVG path-data parser → SwiftUI Path. Covers the commands the logo uses
// (M L H V C, absolute + relative, plus S Q T Z) — enough for these vectors.
enum SVGPathParser {
    static func parse(_ d: String) -> Path {
        var path = Path()
        let chars = Array(d)
        var i = 0
        var cur = CGPoint.zero
        var startPt = CGPoint.zero
        var lastCtrl: CGPoint?
        var cmd: Character = " "

        func skip() {
            while i < chars.count, " ,\n\t\r".contains(chars[i]) { i += 1 }
        }
        func num() -> CGFloat {
            skip()
            var s = ""
            if i < chars.count, chars[i] == "+" || chars[i] == "-" { s.append(chars[i]); i += 1 }
            var dot = false
            while i < chars.count {
                let c = chars[i]
                if c.isNumber { s.append(c); i += 1 }
                else if c == ".", !dot { dot = true; s.append(c); i += 1 }
                else if c == "e" || c == "E" {
                    s.append(c); i += 1
                    if i < chars.count, chars[i] == "+" || chars[i] == "-" { s.append(chars[i]); i += 1 }
                } else { break }
            }
            return CGFloat(Double(s) ?? 0)
        }
        func rel(_ p: CGPoint, _ isRel: Bool) -> CGPoint {
            isRel ? CGPoint(x: cur.x + p.x, y: cur.y + p.y) : p
        }

        while i < chars.count {
            skip()
            if i >= chars.count { break }
            if chars[i].isLetter { cmd = chars[i]; i += 1 }
            let lower = Character(cmd.lowercased())
            let isRel = cmd.isLowercase
            switch lower {
            case "m":
                let p = rel(CGPoint(x: num(), y: num()), isRel)
                cur = p; startPt = p; path.move(to: p)
                cmd = isRel ? "l" : "L"; lastCtrl = nil
            case "l":
                let p = rel(CGPoint(x: num(), y: num()), isRel)
                cur = p; path.addLine(to: p); lastCtrl = nil
            case "h":
                let x = num(); cur = CGPoint(x: isRel ? cur.x + x : x, y: cur.y)
                path.addLine(to: cur); lastCtrl = nil
            case "v":
                let y = num(); cur = CGPoint(x: cur.x, y: isRel ? cur.y + y : y)
                path.addLine(to: cur); lastCtrl = nil
            case "c":
                let c1 = rel(CGPoint(x: num(), y: num()), isRel)
                let c2 = rel(CGPoint(x: num(), y: num()), isRel)
                let e = rel(CGPoint(x: num(), y: num()), isRel)
                path.addCurve(to: e, control1: c1, control2: c2); cur = e; lastCtrl = c2
            case "s":
                let c2 = rel(CGPoint(x: num(), y: num()), isRel)
                let e = rel(CGPoint(x: num(), y: num()), isRel)
                let c1 = lastCtrl.map { CGPoint(x: 2 * cur.x - $0.x, y: 2 * cur.y - $0.y) } ?? cur
                path.addCurve(to: e, control1: c1, control2: c2); cur = e; lastCtrl = c2
            case "q":
                let c = rel(CGPoint(x: num(), y: num()), isRel)
                let e = rel(CGPoint(x: num(), y: num()), isRel)
                path.addQuadCurve(to: e, control: c); cur = e; lastCtrl = c
            case "t":
                let e = rel(CGPoint(x: num(), y: num()), isRel)
                let c = lastCtrl.map { CGPoint(x: 2 * cur.x - $0.x, y: 2 * cur.y - $0.y) } ?? cur
                path.addQuadCurve(to: e, control: c); cur = e; lastCtrl = c
            case "z":
                path.closeSubpath(); cur = startPt; lastCtrl = nil
            default:
                i += 1   // unknown command — skip a char to avoid a stall
            }
        }
        return path
    }
}
